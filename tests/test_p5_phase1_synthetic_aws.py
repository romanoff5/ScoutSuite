CATALOG_PATH = Path(__file__).parent / "data/p5_phase1_synthetic_aws.json"
CATALOG = json.loads(CATALOG_PATH.read_text(encoding="utf-8"))
CASES = CATALOG["cases"]
ACCOUNT = "123456789012"


def _apply_patch(root, patch):
    """Strict, data-only fixture edits; reject missing path and bad operations."""
    path = patch["path"]
    assert isinstance(path, list) and len(path) >= 2, path
    assert path[0] in ("services", "api"), path
    assert patch["op"] in ("set", "append", "delete")
    current = root
    for part in path[:-1]:
        if isinstance(current, list):
            assert isinstance(part, str) and part.isdigit()
            current = current[int(part)]
        else:
            assert isinstance(current, dict) and part in current, (path, part)
            current = current[part]
    last = path[-1]
    if isinstance(current, list):
        assert isinstance(last, str) and last.isdigit(), path
        index = int(last)
        assert 0 <= index < len(current), path
        if patch["op"] == "set":
            current[index] = copy.deepcopy(patch["value"])
        elif patch["op"] == "delete":
            del current[index]
        else:
            raise AssertionError("Append requires a list named by path")
    elif isinstance(current, dict):
        if patch["op"] == "set":
            current[last] = copy.deepcopy(patch["value"])
        elif patch["op"] == "delete":
            assert last in current
            del current[last]
        else:
            assert last in current and isinstance(current[last], list), path
            current[last].append(copy.deepcopy(patch["value"]))
    else:
        raise AssertionError("Cannot mutate a non-container fixture value")


class _PodIdentityClient:
    """AWS-shaped EKS SDK stub for List followed by Describe (not a mock roleArn in List)."""

    def __init__(self, api):
        self.api = api
        self.calls = []

    def list_pod_identity_associations(self, **kwargs):
        self.calls.append(("ListPodIdentityAssociations", kwargs))
        if self.api["failure"] == "list_denied":
            raise PermissionError("synthetic ListPodIdentityAssociations AccessDenied")
        return copy.deepcopy(self.api["list"])

    def describe_pod_identity_association(self, **kwargs):
        self.calls.append(("DescribePodIdentityAssociation", kwargs))
        if self.api["failure"] == "describe_denied":
            raise PermissionError("synthetic DescribePodIdentityAssociation AccessDenied")
        return copy.deepcopy(self.api["describe"])


def _p5_fixture(case):
    """Build normalized service facts from independent, reusable JSON inputs."""
    payload = copy.deepcopy(CATALOG["templates"][case["template"]])
    for change in case["patches"]:
        _apply_patch(payload, change)
    services = payload["services"]
    if "api" in payload:
        api = payload["api"]
        client = _PodIdentityClient(api)
        assert all("roleArn" not in item for item in api["list"]["associations"])
        with patch(
            "ScoutSuite.providers.aws.facade.eks_public.AWSFacadeUtils.get_client",
            return_value=client,
        ):
            collected = asyncio.run(
                EKSPublicFacade(SimpleNamespace(), ACCOUNT)
                .get_pod_identity_associations(CATALOG["region"], "sample")
            )
        assert collected["status"] == case["expected"]["api_status"]
        names = [name for name, _ in client.calls]
        assert names[0] == "ListPodIdentityAssociations"
        assert ("DescribePodIdentityAssociation" in names) == (
            api["failure"] != "list_denied"
        )
        # Collector, not the fixture or the test, supplies verified roleArn.
        cluster = services["eks"]["regions"][CATALOG["region"]]["clusters"]["sample"]
        cluster["pod_identity_inventory_status"] = collected["status"]
        cluster["pod_identity_associations"] = {
            row["id"]: row for row in collected["associations"]
        }
        for association in collected["associations"]:
            assert "policy" not in association  # Never serialize raw session policy.
            if association["detail_collection_status"] != "complete":
                assert association["role_arn"] is None
    return services


def test_p5_phase1_fixture_catalog_contract():
    assert CATALOG["schema"] == "scoutsuite-p5-synthetic-aws-v1"
    assert CATALOG["account_id"] == ACCOUNT
    assert len(CASES) >= 53
    assert len(CATALOG["templates"]) == 10
    ids = [case["id"] for case in CASES]
    assert len(ids) == len(set(ids))
    assert all(case["template"] in CATALOG["templates"] for case in CASES)
    assert all(case["expected"]["graph_status"] in ("complete", "partial")
               for case in CASES)
    assert all(isinstance(case["expected"]["edges"], list) for case in CASES)
    assert {case["template"] for case in CASES} == set(CATALOG["templates"])
    assert {"iam_lambda", "iam_ec2", "ecs_task", "eks_irsa", "eks_pod",
            "s3_bucket", "s3_gov", "kms_policy", "kms_grant",
            "lambda_invoke"} == set(CATALOG["templates"])
    serialized = CATALOG_PATH.read_text(encoding="utf-8")
    assert "AccessKeyId" not in serialized
    assert "SecretAccessKey" not in serialized
    assert "BEGIN PRIVATE KEY" not in serialized
    assert any(case["expected"]["graph_status"] == "partial" for case in CASES)
    assert any(not case["expected"]["edges"] for case in CASES)


def assert_p5_graph_goldens(graph, case):
    """Compare the full observable edge, not just type/source/target.

    These expected values are checked-in fixture data, independent of the
    production graph emitter. Action, exact textual provenance, verification,
    confidence, bounded collection, and non-exploitation flags are immutable.
    """
    expected = case["expected"]
    assert graph["status"] == expected["graph_status"], case["id"]
    for name, status in expected["collection"].items():
        assert graph["collection"][name] == status, (case["id"], name)
    expected_edges = {}
    required = {
        "type", "source", "target", "action", "verification", "confidence",
        "collection", "effective_permission_verified", "execution_verified",
        "evidence",
    }
    for oracle in expected["edges"]:
        assert set(oracle) == required, (case["id"], oracle)
        assert oracle["evidence"] == {
            "source": oracle["source"], "resource": oracle["target"],
            "basis": oracle["evidence"]["basis"],
        }, (case["id"], "provenance")
        assert isinstance(oracle["evidence"]["basis"], str)
        assert oracle["evidence"]["basis"], case["id"]
        assert oracle["confidence"] == (
            "LOW" if oracle["verification"] == "REVIEW" else "MEDIUM")
        assert oracle["collection"] == "complete"
        assert oracle["effective_permission_verified"] is False
        assert oracle["execution_verified"] is False
        ident = hashlib.sha256("|".join(
            (oracle["source"], oracle["target"], oracle["type"],
             oracle["action"])).encode("utf-8")).hexdigest()[:24]
        assert ident not in expected_edges, case["id"]
        expected_edges[ident] = {"id": ident, **oracle}
    # Exact equality detects changed actions, edge IDs, provenance, confidence,
    # unexpected findings, omitted fields and future accidentally "verified"
    # claims. No expected values are inferred from actual graph output.
    assert graph["edges"] == expected_edges, (
        case["id"], graph["edges"], expected_edges)
    assert graph["edges_count"] == len(expected_edges)
    assert graph["nodes_count"] == len(graph["nodes"])
    expected_nodes = {value for edge in expected["edges"]
                      for value in (edge["source"], edge["target"])}
    assert set(graph["nodes"]) == expected_nodes, case["id"]


@pytest.mark.parametrize("case", CASES, ids=[case["id"] for case in CASES])
def test_p5_phase1_normalized_facts_and_independent_attack_path_oracle(case):
    services = _p5_fixture(case)
    # Verify the same production correlator used by ScoutSuite reports.
    graph = annotate_p5d_attack_paths(
        services, sorted(services), CATALOG["account_id"]
    )
    assert_p5_graph_goldens(graph, case)


def test_p5_phase1_fixture_objects_are_not_mutated_across_test_cases():
    original = json.dumps(CATALOG["templates"], sort_keys=True)
    for case in CASES:
        _p5_fixture(case)
    assert json.dumps(CATALOG["templates"], sort_keys=True) == original
